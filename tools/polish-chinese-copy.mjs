function applyReplacements(text) {
  let out = text;
  for (const [from, to] of GLOBAL_REPLACEMENTS) {
    if (out.includes(from)) out = out.split(from).join(to);
  }
  for (const [from, to] of VOICE_REPLACEMENTS) {
    if (out.includes(from)) out = out.split(from).join(to);
  }
  for (const [from, to] of EDITORIAL_REPLACEMENTS) {
    if (out.includes(from)) out = out.split(from).join(to);
  }
  for (const tail of STOCK_TAILS) {
    if (out.includes(tail)) out = out.split(tail).join('');
  }
  return out;
}

